import assert from "node:assert/strict";
import { test } from "node:test";
import { MemoryWorkflowRepository } from "./workflow-store.ts";
const now="2026-11-12T00:00:00.000Z";
test("正式提交快照、反馈、返修与会话隔离",()=>{
  const repository=new MemoryWorkflowRepository();
  const source={id:"node1",date:"2026-11-10",title:"完成实验",note:"原始结果"};
  const submit={type:"report-submit",id:"submission1",mentorId:"T1001",week:"2026-11-09",title:"阶段成果",content:"",sourceNodes:[source]} as const;
  // sourceNodes is copied so later edits cannot rewrite submitted evidence.
  repository.apply("20220001","T1001","student",{...submit,sourceNodes:[source]},now);
  source.note="改过的日常节点";
  assert.equal(repository.list("20220001","T1001").reports[0].revisions[0].sourceNodes![0].note,"原始结果");
  assert.equal(repository.list("20220002","T1001").reports.length,0);
  const review={type:"report-review",reportId:"submission1",revisionId:"submission1",decision:"revision",feedback:"补对照"} as const;
  assert.throws(()=>repository.apply("20220002","T1001","mentor",review,now),/不属于/);
  assert.throws(()=>repository.apply("20220001","T1001","student",review,now),/只有导师/);
  repository.apply("20220001","T1001","mentor",review,now);
  repository.apply("20220001","T1001","student",{...submit,id:"revision2",reportId:"submission1",revisionId:"submission1",content:"已补对照",sourceNodes:[source]},now);
  assert.throws(()=>repository.apply("20220001","T1001","mentor",review,now),/已处理/);
  repository.apply("20220001","T1001","mentor",{...review,revisionId:"revision2",decision:"approved",feedback:""},now);
  const saved=repository.list("20220001","T1001");
  assert.equal(saved.reports[0].revisions.length,2);
  assert.equal(saved.reports[0].revisions[0].sourceNodes![0].note,"原始结果");
  saved.reports.length=0;
  assert.equal(repository.list("20220001","T1001").reports.length,1);
  repository.apply("20220001","T1001","student",{...submit,id:"submission2",sourceNodes:[source]},now);
  repository.apply("20220001","T1001","student",{...submit,id:"submission2",sourceNodes:[source]},now);
  assert.equal(repository.list("20220001","T1001").reports.length,2);
});
test("解惑先在线交流，再双方确认会面，冲突检查跨会话生效",()=>{
  const repository=new MemoryWorkflowRepository();
  repository.apply("20220001","T1001","student",{type:"meeting-create",id:"q1",mentorId:"T1001",title:"实验问题",question:"不确定是否需要面谈"},now);
  assert.equal(repository.list("20220001","T1001").meetings[0].proposals.length,0);
  repository.apply("20220001","T1001","mentor",{type:"question-reply",meetingId:"q1",id:"r1",body:"先在线解释"},now);
  assert.equal(repository.list("20220001","T1001").meetings[0].replies![0].body,"先在线解释");
  const propose={type:"meeting-propose",id:"p1",meetingId:"q1",proposalId:"",start:"2026-11-13T15:00+08:00",end:"2026-11-13T16:00+08:00",place:"302"} as const;
  repository.apply("20220001","T1001","mentor",propose,now);
  const confirm={type:"meeting-respond",meetingId:"q1",proposalId:"p1",action:"confirm",response:""} as const;
  assert.throws(()=>repository.apply("20220001","T1001","mentor",confirm,now),/对方确认/);
  repository.apply("20220001","T1001","student",confirm,now);
  repository.apply("20220002","T1001","student",{type:"meeting-create",id:"q2",mentorId:"T1001",title:"另一问题",question:"想面谈"},now);
  repository.apply("20220002","T1001","student",{...propose,id:"p2",meetingId:"q2"},now);
  assert.throws(()=>repository.apply("20220002","T1001","mentor",{...confirm,meetingId:"q2",proposalId:"p2"},now),/已有会面/);
  repository.apply("20220001","T1001","student",{type:"question-status",meetingId:"q1",resolved:true},now);
  assert.equal(repository.list("20220001","T1001").meetings[0].status,"confirmed");
  repository.apply("20220001","T1001","student",{...confirm,action:"cancel"},now);
  repository.apply("20220002","T1001","mentor",{...confirm,meetingId:"q2",proposalId:"p2"},now);
  assert.equal(repository.list("20220002","T1001").meetings[0].status,"confirmed");
});
